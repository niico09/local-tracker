package web_test

import (
	"context"

	"local-tracker/internal/coverfetch"
)

// coverStub is the network-free CoverFinder the harness wires: search returns
// one fixed candidate and fetch returns a tiny valid PNG, so the whole cover
// search flow can be exercised without leaving the machine.
type coverStub struct{}

func (coverStub) Search(ctx context.Context, query string) ([]coverfetch.Candidate, error) {
	return []coverfetch.Candidate{{
		Label:    "Stub · " + query,
		ThumbURL: "https://covers.openlibrary.org/b/id/1-M.jpg",
		FullURL:  "https://covers.openlibrary.org/b/id/1-L.jpg",
	}}, nil
}

func (coverStub) Fetch(ctx context.Context, url string) ([]byte, string, error) {
	return tinyPNG, "image/png", nil
}

